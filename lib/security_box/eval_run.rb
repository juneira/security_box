# frozen_string_literal: true

require "json"
require "securerandom"
require "tmpdir"

module SecurityBox
  # One :oneshot evaluation against a pre-built runtime (Engine + Module +
  # Linker). This is the shared core used by Sandbox (main Ractor, threads)
  # and by RactorPool workers (one Ractor per worker) — both follow the same
  # protocol: sandbox-exclusive tmpdir mounted as /work, per-eval token via
  # ENV, envelope read back from /work/out.json (stdout sentinel fallback),
  # fuel + epoch deadlines per evaluation, and explicit read-only-by-default
  # host-folder mounts (stage 5) validated per eval.
  #
  # Everything here is self-contained per call: no shared mutable state, safe
  # to run concurrently from multiple Ractors/threads as long as each caller
  # owns its Engine/Module/Linker (Ractors) or shares them thread-safely
  # (wasmtime Engine/Module/Linker are thread-safe).
  module EvalRun
    GUEST_ENTRYPOINT = "/src/main.rb"
    CODE_FILE = "code.rb"
    RESULT_FILE = "out.json"
    TOKEN_ENV_VAR = "SB_TOKEN"

    class << self
      # Runs `code` once and returns a Result. `config` is a Configuration
      # (read-only); `token` is the per-eval random token generated by the
      # caller (SecureRandom is not guaranteed Ractor-safe, so workers
      # receive it pre-generated).
      def run(engine:, module_:, linker:, config:, code:, token:)
        stdout = +""
        stderr = +""
        t0 = monotonic_ms

        # Mounts reference host paths that can disappear between building the
        # configuration and this eval; fail here with a clear note instead of
        # letting Wasmtime::Store.new raise an opaque error mid-setup.
        mount_errors = mount_errors(config)
        unless mount_errors.empty?
          return Result.new(status: :sandbox_error, stderr: mount_errors.join("\n") << "\n",
                            duration_ms: monotonic_ms - t0)
        end

        Dir.mktmpdir("security_box") do |workdir|
          File.write(File.join(workdir, CODE_FILE), code)
          # Per-eval RPC state (stage 6): the /work tmpdir plus the
          # configuration's handlers (nil when none are configured — the
          # import is still defined, guest calls get a rescuable error).
          # The calls array doubles as the Result transcript.
          rpc_data = GuestRpc.store_data(
            workdir, config.rpcs.empty? ? nil : config.rpcs
          )
          envelope = nil
          status = nil
          fuel_used = nil

          store = nil
          begin
            store = Wasmtime::Store.new(
              engine,
              rpc_data,
              wasi_p1_config: build_wasi(workdir, stdout, stderr, config, token),
              limits: { memory_size: config.memory_size }
            )
            store.set_fuel(config.effective_fuel)
            instance = linker.instantiate(store, module_)
            store.set_epoch_deadline(epoch_ticks(config))
            status = invoke_guest(instance, store)
            fuel_used = config.effective_fuel - store.get_fuel unless status == :timeout
            envelope = read_envelope(workdir, stdout, token)
          rescue Wasmtime::Error => e
            # Instantiation can fail before the guest ever runs (e.g. a
            # memory_size below the module's declared minimum pages).
            status = :sandbox_error
            stderr << "security_box: #{e.class}: #{e.message}\n"
          ensure
            store&.close
          end

          build_result(status, envelope, stdout, stderr, fuel_used,
                       monotonic_ms - t0, rpc_data[:rpc]&.fetch(:calls))
        end
      end

      private

      def build_wasi(workdir, stdout, stderr, config, token)
        wasi = Wasmtime::WasiConfig.new
                .set_stdin_string("")
                .set_stdout_buffer(stdout, config.stdout_limit)
                .set_stderr_buffer(stderr, config.stderr_limit)
                .set_argv(["ruby", GUEST_ENTRYPOINT])
                .set_env(config.env.merge(TOKEN_ENV_VAR => token))
                .set_mapped_directory(workdir, "/work", :read_write)
        # Explicit mounts come after /work; Configuration validation already
        # guarantees no guest-path overlap with /work, /usr or /src.
        config.mounts.reduce(wasi) do |wasi_config, mount|
          wasi_config.set_mapped_directory(mount[:host], mount[:guest], mount[:mode])
        end
      end

      # Host-side mount validation for this eval (configuration-level shape
      # and collision rules are enforced in Configuration::Mounts).
      def mount_errors(config)
        config.mounts.reject { |mount| File.directory?(mount[:host]) }.map do |mount|
          "security_box: mount #{mount[:host].inspect} (guest #{mount[:guest].inspect}): " \
            "host path does not exist or is not a directory"
        end
      end

      def epoch_ticks(config)
        [config.timeout_ms / config.epoch_interval_ms + 1, 1].max
      end

      def invoke_guest(instance, store)
        instance.invoke("_start")
        :ok
      rescue Wasmtime::WasiExit => e
        handle_wasi_exit(e, store)
      rescue Wasmtime::Trap => e
        map_trap(e, store)
      rescue Wasmtime::Error
        # Unexpected runtime error (non-trap): treated as a sandbox failure.
        :sandbox_error
      end

      def handle_wasi_exit(_exit_error, store)
        # The guest rescues SystemExit; a WasiExit here means exit! or a guest
        # crash before the envelope was written.
        store.linear_memory_limit_hit? ? :memory_limit : :sandbox_error
      end

      def map_trap(trap, store)
        case trap.code
        when :interrupt then :timeout
        when :out_of_fuel then :fuel_exhausted
        when :memory_out_of_bounds then :memory_limit
        else
          store.linear_memory_limit_hit? ? :memory_limit : :sandbox_error
        end
      end

      def read_envelope(workdir, stdout, token)
        # Preferred channel: /work/out.json. Fallback: sentinel line on stdout.
        # Both go through the same strict validation (schema + token).
        Envelope.parse(read_result_file(workdir), token) ||
          Envelope.from_stdout(stdout, token)
      end

      def read_result_file(workdir)
        File.read(File.join(workdir, RESULT_FILE))
      rescue SystemCallError
        nil
      end

      def build_result(status, envelope, stdout, stderr, fuel_used, duration_ms, rpc_calls = nil)
        rpcs = rpc_calls && !rpc_calls.empty? ? rpc_calls.each(&:freeze).freeze : nil
        if envelope.nil?
          status = :sandbox_error if status == :ok
          return Result.new(
            status: status, stdout: stdout, stderr: stderr,
            fuel_used: fuel_used, duration_ms: duration_ms, rpcs: rpcs
          )
        end

        guest_error = envelope["error"]
        if envelope["ok"]
          Result.new(
            status: status, value: envelope["value"], stdout: stdout, stderr: stderr,
            fuel_used: fuel_used, duration_ms: duration_ms,
            guest_duration_ms: envelope["duration_ms"], rpcs: rpcs
          )
        elsif guest_memory_error?(guest_error)
          # The guest hit the store memory limit through the Ruby interpreter
          # (NoMemoryError instead of a wasm trap) — report it as a limit, not
          # a user error.
          Result.new(
            status: :memory_limit, error: guest_error, stdout: stdout, stderr: stderr,
            fuel_used: fuel_used, duration_ms: duration_ms,
            guest_duration_ms: envelope["duration_ms"], rpcs: rpcs
          )
        else
          Result.new(
            status: :error, error: guest_error, stdout: stdout, stderr: stderr,
            fuel_used: fuel_used, duration_ms: duration_ms,
            guest_duration_ms: envelope["duration_ms"], rpcs: rpcs
          )
        end
      end

      def guest_memory_error?(guest_error)
        guest_error.is_a?(Hash) && guest_error["class"] == "NoMemoryError"
      end

      def monotonic_ms
        Process.clock_gettime(Process::CLOCK_MONOTONIC) * 1000
      end
    end
  end
end
